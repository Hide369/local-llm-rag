"""クエリに含まれる既知の表記ゆれを展開する。

汎用的な算用数字⇔漢数字の変換はしない。「三六協定」は桁の位取り読み
（36→三十六）ではなく「サブロク」と読む当て字であり、一般的な数値→漢数字
変換をかけても「三十六協定」にしかならず一致しない。用語ごとに個別対応する
以外に正しい表記へは辿り着けない。

置き換えではなく継ぎ足しなのは、ユーザーが打った表記も検索対象に残すため。
BM25の文字bigram一致（ingest/lexical.py）とベクトル埋め込みの両方に、
コーパス側の表記（三六協定）を追加で渡すことで、字面と意味の両方の距離を
縮める。

継ぎ足す語に「について」を付けるのは、bge-m3が単語だけの短いクエリを
文章形式の質問より遠くに埋め込むため。実測: 「三六協定」単体は距離0.506で
しきい値0.50を超えて圏外に落ちるが、「三六協定について」は0.470まで縮まる
（DB: モデル就業規則.pdf、495チャンク、scripts/check_retrieval.py と同一条件）。

カタカナの俗称「サブロク協定」は対象に含めない。同じ要領で展開しても実測
0.551までしか縮まらず、しきい値0.50を超えたまま圏外に落ちる
（bge-m3がこの表記をコーパスの文章とうまく結び付けられていない）。
効果を確認できていない展開を残すと、動かない期待だけを残すことになる。
"""

# キー: ユーザーが打ちうる表記。値: コーパス上の正式表記に「について」を付けた形。
_SYNONYMS: dict[str, str] = {
    "36協定": "三六協定について",
}


def expand_query(query: str) -> str:
    """既知の表記ゆれがあれば、対応する表記を末尾に継ぎ足す。"""
    additions = [
        expansion
        for term, expansion in _SYNONYMS.items()
        if term in query and expansion not in query
    ]
    if not additions:
        return query
    # 同じ展開先を二重に足さない（36協定とサブロク協定が両方入っていても1回だけ）。
    unique_additions = list(dict.fromkeys(additions))
    return " ".join([query, *unique_additions])
