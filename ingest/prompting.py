"""プロンプト組み立てと取り込み結果の要約。

UIから呼ばれるがUIには依存しない。Streamlitスクリプトに置くと、テストが
インポートしただけでスクリプト全体が走り本番DBを開いてしまうため、ここに分離する。
"""
from ingest.retrieval import RELEVANCE_THRESHOLD


def build_prompt(question: str, hits) -> str:
    """検索結果を今回の質問にだけ添える。

    履歴には生の質問を残す。ここで作った文字列を履歴に入れると、
    次のターン以降に古いコンテキストが混ざる。

    しきい値0.50は「関連度が高い」ことまでは保証しない。挨拶のような
    意味的に空な入力は、コーパスの重心付近に落ちて距離0.349〜0.381になり、
    しきい値では弾けない（ingest/retrieval.pyのコメント参照）。そのため
    ここでは、根拠が質問に無関係なら使わずにその旨を答えるようモデルに
    明示的に指示する。距離やUI側でのフィルタでは解決しない問題であり、
    プロンプトが最後の砦になる。

    「資料にない主体を補わない」の指示も同じ理由でここに置く。実測では、
    「Claude Code 法人導入ガイド」スライドの図の説明（SuperPowersプラグインの
    紹介）を根拠に、資料には無い「弊社が提供する」という主語をgpt-oss:20bが
    勝手に補った。資料が社内向け導入ガイドという文脈から誤って類推したと
    見られる。個別の固有名詞（Anthropic社等）を教える方法は他の外部ツール名
    には効かないため、「主体を根拠なく補わない」という一般則にしてある。
    """
    if not hits:
        # ここで質問をそのまま返すと、system prompt の「あなたは有能な
        # アシスタントです」だけが残り、モデルは知識で答えにいく。根拠が
        # 1件も無いときこそ歯止めが要る。
        return (
            "社内文書を検索しましたが、この質問に関連する記述は見つかりませんでした。"
            "推測で答えず、社内文書からは回答できない旨を伝えてください。\n\n"
            f"ユーザーの質問: {question}"
        )
    context = "\n\n".join(f"[{hit.citation}]\n{hit.text}" for hit in hits)
    return (
        "以下の社内文書を参考に回答してください。"
        "回答の根拠にした箇所は [ ] 内の出典を示してください。"
        "参考文書が質問と無関係、または回答の根拠にならない場合は、"
        "文書の内容を無理に使わず、社内文書からは回答できない旨を伝えてください。"
        "資料に明記されていない事実（提供元・開発元・保有関係などの主体）を"
        "推測で補わないでください。\n\n"
        f"{context}\n\nユーザーの質問: {question}"
    )


def build_catalog_prompt(question: str, table: str) -> str:
    """絞り込んだ一覧だけを根拠に答えさせる。

    この表は where で引いており、条件に合うものは全件そろっている。裏を返せば
    表に無いものは条件に合わないということなので、補完の余地は一切ない。
    実測では、表を渡さずに散文チャンクだけを渡したとき、モデルは型番から
    容量を推測して誤った数値を答えた。

    出典の示し方は散文の検索結果と違う。一覧の1行が1つの製品仕様書なので、
    型番がそのまま出典になる。ファイル名は渡していない（`ingest/catalog.py` の
    `_row` 参照）。

    文章で答えさせる指示と文例を入れている。指示だけでは足りず、実測（4回ずつ）では
    「文章で書き、行を貼り付けるな」だけのときは4回とも表の行を丸写しし、文例を
    足して初めて4回とも文章になった。文例の型番と数値は AAA-000 のような架空の
    ものにしてある。実在の値を書くと、モデルがその値をそのまま答えに写す。
    """
    return (
        "以下は社内の資料を条件で絞り込んだ一覧です。"
        "各行は「型番 | 属性」の並びです。"
        "この一覧に載っている事実だけを使って回答してください。"
        "一覧に無い型番や数値を推測して補ってはいけません。"
        "製品は型番で示してください。"
        "回答は日本語の文章で書いてください。"
        "「型番 | 属性=値」という一覧の行をそのまま貼り付けてはいけません。"
        "数値と型番は文に織り込んでください。"
        "同じ値の製品が複数あるときは、その全部を挙げてください。"
        "例:「最大◯◯kgです。条件に合うのは型番AAA-000（◯◯kg）と"
        "型番BBB-000（◯◯kg）の2機種です。」\n\n"
        f"{table}\n\nユーザーの質問: {question}"
    )


def format_report(report) -> str:
    lines = [
        f"取り込み: {sum(report.indexed.values())}チャンク / {len(report.indexed)}ファイル",
        f"スキップ: {len(report.skipped)}ファイル",
        f"削除: {len(report.removed)}ファイル",
    ]
    for source, message in report.failed.items():
        lines.append(f"失敗 {source}: {message}")
    return "\n".join(lines)


def format_hit_caption(hit) -> str:
    """出典と、どちらのアームが拾ったかを1行で示す。

    経路を見せるのは、しきい値を調整するときにどちらが効いたのかを画面から
    読み取れるようにするためである。BM25側は下限を設けていないので（圏内判定は
    ベクトル側の距離が受け持つ）、スコアはしきい値ではなく実測値として出す。

    BM25だけで当たったヒットは距離を持たず、ベクトルだけで当たったヒットは
    スコアを持たない。素直に書式化すると 'None' が画面に出る。

    distance が None のヒットは「しきい値を超えた」のではなく、ベクトル側の
    CANDIDATE_COUNT件の候補に入らず距離を測っていない。31位で距離0.49という
    こともあり得るため、「圏外」と書くと測定していない事実を測定した事実
    であるかのように誤って伝える。
    """
    distance = (
        f"cosine距離 {hit.distance:.3f}（しきい値 {RELEVANCE_THRESHOLD}）"
        if hit.distance is not None
        else "cosine距離 未計測（BM25で採用）"
    )
    score = (
        f"BM25 {hit.bm25_score:.2f}" if hit.bm25_score is not None else "BM25 一致なし"
    )
    return f"{hit.citation} ／ {distance} ／ {score}"
